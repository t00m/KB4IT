from dataclasses import dataclass, field

import markdown

from kb4it.core.exceptions import ConfigError
from kb4it.core.log import get_logger
from kb4it.core.mdlinks import MdLinkExtension
from kb4it.core.mdrich import MATH_EXTENSIONS, RichContentExtension

log = get_logger(__name__)

# Always on: the documented KB4IT Markdown dialect.
BASE_EXTENSIONS = ["extra", "admonition", "toc", "sane_lists"]
HIGHLIGHT_MODES = ("client", "pygments", "none")
# PyMdown extensions that highlight code through pymdownx.highlight.
_PYMDOWNX_HIGHLIGHTERS = ("pymdownx.superfences", "pymdownx.highlight", "pymdownx.inlinehilite")

# Package to install for well-known extension modules, for the error hint.
_PACKAGES = {"pymdownx": "pymdown-extensions", "markdown_katex": "markdown-katex",
             "mdx_truly_sane_lists": "mdx-truly-sane-lists"}


@dataclass
class MarkdownSettings:
    extensions: list = field(default_factory=list)          # user extensions, after the base ones
    extension_configs: dict = field(default_factory=dict)
    highlight: str = "client"
    pygments_style: str = "default"
    pygments_style_dark: str = "monokai"
    sanitize: bool = False                                  # clean each document's HTML with nh3

    def all_extensions(self):
        """Extension list for one python-markdown instance (a fresh link rewriter each time)."""
        names = list(BASE_EXTENSIONS)
        if self.highlight == "pygments":
            names.append("codehilite")
        if self._uses_pymdownx_highlight() and "pymdownx.highlight" not in self.extensions:
            # Loaded explicitly so its use_pygments setting (see all_configs) reaches superfences.
            names.append("pymdownx.highlight")
        names += [name for name in self.extensions if name not in names]
        if not any(name in MATH_EXTENSIONS for name in self.extensions):
            names.append(RichContentExtension())
        return names + [MdLinkExtension()]

    def _uses_pymdownx_highlight(self):
        return any(name in _PYMDOWNX_HIGHLIGHTERS for name in self.extensions)

    def all_configs(self):
        configs = dict(self.extension_configs)
        if self.highlight == "pygments":
            configs.setdefault("codehilite", {"css_class": "highlight", "guess_lang": False})
        if self._uses_pymdownx_highlight():
            # Pygments markup only when KB4IT writes pygments.css; otherwise plain language-* classes
            # for highlight.js (client) or for no highlighting at all (none).
            highlight = dict(configs.get("pymdownx.highlight", {}))
            highlight.setdefault("use_pygments", self.highlight == "pygments")
            configs["pymdownx.highlight"] = highlight
        return configs

    def new_markdown(self):
        return markdown.Markdown(extensions=self.all_extensions(), extension_configs=self.all_configs())


def pygments_css(settings: MarkdownSettings) -> str:
    """Stylesheet for build-time highlighting: the light style, and the dark one for dark colour schemes."""
    from pygments.formatters import HtmlFormatter
    light = HtmlFormatter(style=settings.pygments_style).get_style_defs(".highlight")
    dark = HtmlFormatter(style=settings.pygments_style_dark).get_style_defs(".highlight")
    indented = "\n".join("  " + line for line in dark.splitlines())
    return f"/* Generated by KB4IT from Pygments styles. */\n{light}\n\n@media (prefers-color-scheme: dark) {{\n{indented}\n}}\n"


# What python-markdown, its bundled extensions, codehilite and PyMdown produce. Anything else,
# and every script, style element, event handler or javascript: link, is removed.
SANITIZE_TAGS = {
    "a", "abbr", "b", "blockquote", "br", "caption", "code", "col", "colgroup", "dd", "del", "details",
    "div", "dl", "dt", "em", "figcaption", "figure", "h1", "h2", "h3", "h4", "h5", "h6", "hr", "i", "img",
    "input", "ins", "kbd", "label", "li", "mark", "ol", "p", "pre", "s", "small", "span", "strong", "sub",
    "summary", "sup", "table", "tbody", "td", "tfoot", "th", "thead", "tr", "u", "ul",
}
SANITIZE_ATTRIBUTES = {
    "*": {"class", "id", "title", "lang", "dir"},
    "a": {"href", "name", "rel"},
    "img": {"src", "alt", "width", "height", "loading"},
    "th": {"style", "align", "colspan", "rowspan"},
    "td": {"style", "align", "colspan", "rowspan"},
    "col": {"span"},
    "colgroup": {"span"},
    "ol": {"start", "type", "reversed"},
    "li": {"value"},
    "input": {"type", "checked", "disabled", "name"},
    "label": {"for"},
    "details": {"open"},
    "pre": {"data-linenos"},
    "abbr": {"title"},
}
SANITIZE_SCHEMES = {"http", "https", "mailto", "tel", "ftp", "data"}


def _keep_attribute(tag, attribute, value):
    """data: URLs only as image sources (inline pictures); never in links."""
    if attribute in ("href", "src") and value.strip().lower().startswith("data:"):
        return value if tag == "img" and value.strip().lower().startswith("data:image/") else None
    return value


def sanitize_html(html: str) -> str:
    """Clean a document's compiled HTML with the allow-list above (markdown.sanitize)."""
    import nh3
    return nh3.clean(html, tags=SANITIZE_TAGS, attributes=SANITIZE_ATTRIBUTES, url_schemes=SANITIZE_SCHEMES,
                     clean_content_tags={"script", "style"}, attribute_filter=_keep_attribute,
                     filter_style_properties={"text-align"}, link_rel=None, strip_comments=True)


def _package_hint(name):
    top = name.split(".", 1)[0].split(":", 1)[0]
    return _PACKAGES.get(top, top)


def load_settings(repo: dict) -> MarkdownSettings:
    """Read and check the markdown block; raise ConfigError naming the problem."""
    block = repo.get("markdown") or {}
    if not isinstance(block, dict):
        raise ConfigError("repo.json 'markdown' must be an object")
    extensions = block.get("extensions", [])
    if not isinstance(extensions, list) or not all(isinstance(e, str) and e.strip() for e in extensions):
        raise ConfigError("repo.json 'markdown.extensions' must be a list of extension names")
    configs = block.get("extension_configs", {})
    if not isinstance(configs, dict) or not all(isinstance(v, dict) for v in configs.values()):
        raise ConfigError("repo.json 'markdown.extension_configs' must map extension names to objects")
    highlight = block.get("highlight", "client")
    if highlight not in HIGHLIGHT_MODES:
        raise ConfigError(f"repo.json 'markdown.highlight' must be one of {', '.join(HIGHLIGHT_MODES)}")
    sanitize = block.get("sanitize", False)
    if not isinstance(sanitize, bool):
        raise ConfigError("repo.json 'markdown.sanitize' must be true or false")
    settings = MarkdownSettings(
        extensions=[e.strip() for e in extensions], extension_configs=configs, highlight=highlight,
        pygments_style=block.get("pygments_style", "default"),
        pygments_style_dark=block.get("pygments_style_dark", "monokai"), sanitize=sanitize)
    _check_loadable(settings)
    return settings


def _check_loadable(settings):
    """Load every extension once, so a missing package fails before any page is built."""
    for name in settings.extensions + (["codehilite"] if settings.highlight == "pygments" else []):
        try:
            markdown.Markdown(extensions=[name], extension_configs={
                k: v for k, v in settings.all_configs().items() if k == name})
        except ImportError as error:
            hint = "pygments" if name == "codehilite" else _package_hint(name)
            log.error(f"[COMPILER] MD_EXTENSION_MISSING name={name} hint=pip install {hint}")
            raise ConfigError(f"Markdown extension '{name}' is not installed (pip install {hint}): {error}") from error
        except Exception as error:
            log.error(f"[COMPILER] MD_EXTENSION_INVALID name={name} error={error}")
            raise ConfigError(f"Markdown extension '{name}' cannot load: {error}") from error
    if settings.sanitize:
        try:
            import nh3  # noqa: F401
        except ImportError as error:
            log.error("[COMPILER] MD_EXTENSION_MISSING name=nh3 hint=pip install nh3")
            raise ConfigError("markdown.sanitize needs the nh3 package (pip install nh3, or KB4IT[extras])") from error
    if settings.highlight == "pygments":
        try:
            import pygments  # noqa: F401  codehilite silently skips colouring without it
        except ImportError as error:
            log.error("[COMPILER] MD_EXTENSION_MISSING name=pygments hint=pip install pygments")
            raise ConfigError("markdown.highlight 'pygments' needs the Pygments package") from error
